#!/usr/bin/env node
/**
 * Regenerate scripts/play/play-apps.json from apk-catalog.json + My-Projects.json.
 * Only includes apps that already have Android APKs (status: available).
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const catalog = JSON.parse(await readFile(path.join(root, 'apk-catalog.json'), 'utf8'));
const projects = JSON.parse(await readFile(path.join(root, 'My-Projects.json'), 'utf8'));
const outPath = path.join(root, 'scripts/play/play-apps.json');

const LOCAL_APPS = {
  'mbc-store': {
    build: { type: 'gradle', projectDir: 'download/android' },
    signing: {
      keystore: 'secrets/mbc-upload.keystore',
      alias: 'mbc-upload',
      storePasswordEnv: 'MBC_UPLOAD_KEYSTORE_PASSWORD',
      keyPasswordEnv: 'MBC_UPLOAD_KEY_PASSWORD',
    },
  },
  navigate: {
    build: { type: 'capacitor', projectDir: 'Navigate', androidDir: 'Navigate/android' },
    signing: {
      keystore: 'Navigate/android/navigate-release.keystore',
      alias: 'navigate',
      storePasswordEnv: 'NAVIGATE_KEYSTORE_PASSWORD',
      keyPasswordEnv: 'NAVIGATE_KEY_PASSWORD',
      defaultStorePassword: 'mbcnavigate',
      defaultKeyPassword: 'mbcnavigate',
    },
  },
};

const DEFAULT_SIGNING = {
  keystore: 'secrets/mbc-upload.keystore',
  alias: 'mbc-upload',
  storePasswordEnv: 'MBC_UPLOAD_KEYSTORE_PASSWORD',
  keyPasswordEnv: 'MBC_UPLOAD_KEY_PASSWORD',
};

function projectForSlug(slug) {
  return projects.find((p) => p.slug === slug);
}

function packageIdFor(app, project) {
  return app.android?.packageId || guessPackageId(slugFromApp(app), project);
}

function slugFromApp(app) {
  return app.slug;
}

function guessPackageId(slug, project) {
  const map = {
    findr: 'com.themarkkbradoncollective.findr',
    buynothing: 'org.sacramentobuynothing.app',
  };
  return map[slug] || `com.themarkkbradoncollective.${slug.replace(/-/g, '')}`;
}

const apps = [];

if (catalog.storeApp?.packageId) {
  apps.push({
    slug: 'mbc-store',
    name: catalog.storeApp.name || 'MBC Store',
    packageId: catalog.storeApp.packageId,
    version: catalog.storeApp.version,
    versionCode: catalog.storeApp.versionCode,
    github: 'https://github.com/TheMarkkBradonCollective/main',
    apkArchives: 0,
    ...LOCAL_APPS['mbc-store'],
  });
}

for (const app of catalog.apps) {
  if (app.android?.status !== 'available') continue;
  if (app.slug === 'navigate' || app.slug === 'mbc-store') {
    if (app.slug === 'navigate') {
      const local = LOCAL_APPS.navigate;
      const project = projectForSlug('navigate');
      apps.push({
        slug: 'navigate',
        name: app.name,
        packageId: app.android.packageId || 'com.themarkkbradoncollective.navigate',
        version: app.android.version,
        versionCode: app.android.versionCode,
        github: project?.github || 'https://github.com/TheMarkkBradonCollective/Navigate',
        apkArchives: app.android.archives?.length || 0,
        ...local,
      });
    }
    continue;
  }

  const project = projectForSlug(app.slug);
  const archives = app.android.archives?.length || 0;
  apps.push({
    slug: app.slug,
    name: app.name,
    packageId: packageIdFor(app, project),
    version: app.android.version,
    versionCode: app.android.versionCode,
    github: project?.github || project?.apkGithub || null,
    apkArchives: archives,
    build: {
      type: 'capacitor',
      clone: true,
    },
    signing: { ...DEFAULT_SIGNING },
  });
}

const config = {
  generatedAt: new Date().toISOString(),
  note: 'Auto-generated by scripts/play/sync-play-apps.mjs — run npm run play:sync-apps to refresh.',
  developerAccount: 'themarkkbrandoncollective@gmail.com',
  defaultTrack: 'internal',
  outputDir: 'aabs',
  apps,
};

await writeFile(outPath, JSON.stringify(config, null, 2) + '\n');
console.log(`Wrote ${outPath} — ${apps.length} apps with APKs`);
for (const app of apps) {
  const archives = app.apkArchives ? ` (+${app.apkArchives} APK archives)` : '';
  console.log(`  ${app.slug} v${app.version || '?'} ${app.packageId}${archives}`);
}
